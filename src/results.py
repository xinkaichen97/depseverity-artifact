"""Main results table: every (condition, model) on the frozen test split."""
import json
from pathlib import Path

import numpy as np

import aggregate as A
import conditions as C
import evaluate as E

ROOT = Path(__file__).resolve().parents[1]
MODELS = ["ollama:qwen3.5:9b", "deepseek:deepseek-flash", "anthropic:claude-sonnet-5"]
SHORT = {"ollama:qwen3.5:9b": "qwen3.5:9b",
         "deepseek:deepseek-flash": "DeepSeek-V4.1-Flash",
         "deepseek:deepseek-v4-pro": "deepseek-v4-pro (retired)",
         "anthropic:claude-sonnet-5": "claude-sonnet-5"}
CONDS = ("C1", "C2", "C3", "C4")


def label_preds(cond, model):
    recs = A.load_run(cond, model, "test")
    ok = [r for r in recs if "error" not in r and r.get("pred")]
    if not ok:
        return None
    y = np.array([C.LABELS.index(r["gold"]) for r in ok])
    p = np.array([C.LABELS.index(r["pred"]) for r in ok])
    n_err = sum("error" in r for r in recs)
    n_pf = sum(r.get("parse_error") is not None for r in recs if "error" not in r)
    return y, p, {"n": len(recs), "usable": len(ok), "errors": n_err, "parse_fail": n_pf}


def main():
    rows, raw = [], {}
    for model in MODELS:
        for cond in CONDS:
            try:
                if cond in ("C3", "C4"):
                    agg = A.build(model, condition=cond)
                    y = np.array(agg["y_true"]); p = np.array(agg["y_pred"])
                    info = {"n": agg["n_test"], "usable": agg["n_test"], "errors": 0,
                            "parse_fail": 0, "cutoffs": agg["cutoffs"],
                            "absent_rate": agg["collapse_test"]["absent_rate"]}
                    # parse failures live in the raw run, before aggregation
                    recs = A.load_run(cond, model, "test")
                    info["errors"] = sum("error" in r for r in recs)
                    info["parse_fail"] = sum(r.get("parse_error") is not None
                                             for r in recs if "error" not in r)
                else:
                    got = label_preds(cond, model)
                    if got is None:
                        continue
                    y, p, info = got
            except SystemExit:
                continue
            if info["errors"] or len(y) < 700:
                rows.append((SHORT[model], cond, None, info)); continue
            m = E.evaluate(y, p)
            rows.append((SHORT[model], cond, m, info))
            raw[f"{SHORT[model]}|{cond}"] = {"metrics": m, "info": info}

    out = ["# Main results — test split (n=706, 56 gold-Severe)\n",
           "Bootstrap 95% CIs over the test set (2000 resamples). Single run per cell;",
           "temperature 0 where the API allows it. Generated by `src/results.py`.\n",
           "| Model | Cond | QWK [95% CI] | MAE | Acc | Macro-F1 | Severe missed | Under | Over |",
           "|---|---|---|---:|---:|---:|---|---:|---:|"]
    for name, cond, m, info in rows:
        if m is None:
            out.append(f"| {name} | {cond} | _incomplete ({info['usable']}/{info['n']}, "
                       f"{info['errors']} errors)_ | | | | | | |")
            continue
        out.append(
            f"| {name} | {cond} | **{m['qwk']:.3f}** [{m['qwk_ci'][0]:.3f}, {m['qwk_ci'][1]:.3f}] "
            f"| {m['mae']:.3f} | {m['acc']:.3f} | {m['macro_f1']:.3f} "
            f"| {m['severe_missed_rate']:.3f} ({m['severe_missed_n']}/{m['n_gold_severe']}) "
            f"| {m['under_rate']:.3f} | {m['over_rate']:.3f} |")

    out += ["", "## Method cost and reliability\n",
            "| Model | Cond | parse failures | notes |", "|---|---|---:|---|"]
    for name, cond, m, info in rows:
        note = ""
        if cond in ("C3", "C4") and "cutoffs" in info:
            cuts = ", ".join(f"{float(c):g}" for c in info["cutoffs"])
            note = f"cutoffs [{cuts}], absent used {info['absent_rate']*100:.2f}% of judgments"
        out.append(f"| {name} | {cond} | {info['parse_fail']} | {note} |")

    # Paired comparisons: same posts, so test the difference directly.
    preds = {}
    for model in MODELS:
        for cond in CONDS:
            try:
                if cond in ("C3", "C4"):
                    agg = A.build(model, condition=cond)
                    preds[(SHORT[model], cond)] = (np.array(agg["y_true"]),
                                                   np.array(agg["y_pred"]))
                else:
                    got = label_preds(cond, model)
                    if got and len(got[0]) >= 700:
                        preds[(SHORT[model], cond)] = (got[0], got[1])
            except SystemExit:
                pass

    out += ["", "## Paired comparisons (same test posts, 4000 bootstrap resamples)\n",
            "| Model | Comparison | dQWK [95% CI] | sig | dSevere-missed [95% CI] | sig |",
            "|---|---|---|:--:|---|:--:|"]
    for model in MODELS:
        n = SHORT[model]
        for a, b in (("C1", "C2"), ("C2", "C3"), ("C2", "C4"), ("C3", "C4"), ("C1", "C3")):
            if (n, a) not in preds or (n, b) not in preds:
                continue
            ya, pa = preds[(n, a)]
            _, pb = preds[(n, b)]
            q = E.paired_delta(ya, pa, pb, "qwk")
            sv = E.paired_delta(ya, pa, pb, "severe_missed")
            out.append(
                f"| {n} | {b} - {a} | {q['delta']:+.3f} [{q['ci'][0]:+.3f}, {q['ci'][1]:+.3f}] "
                f"| {'**yes**' if q['excludes_zero'] else 'no'} "
                f"| {sv['delta']:+.3f} [{sv['ci'][0]:+.3f}, {sv['ci'][1]:+.3f}] "
                f"| {'**yes**' if sv['excludes_zero'] else 'no'} |")

    (ROOT / "results/main_results.md").write_text("\n".join(out))
    (ROOT / "results/main_results.json").write_text(json.dumps(raw, indent=2, default=float))
    print("\n".join(out))


if __name__ == "__main__":
    main()
